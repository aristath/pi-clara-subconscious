import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { startService } from '../src/service.js';
import { fixture } from './helpers.js';

const repository = fileURLToPath(new URL('..', import.meta.url));
test('clean tarball installs, contains only public artifacts, and loads through normal Pi package discovery', async t => {
  const f = fixture(t, { initialRestMs: 60000 });
  const packed = JSON.parse(execFileSync('npm', ['pack', '--json', '--pack-destination', f.root], { cwd: repository, encoding: 'utf8' }));
  const result = Array.isArray(packed) ? packed[0] : Object.values(packed)[0];
  const files = result.files.map(file => file.path);
  assert.equal(files.includes('src/extension.js'), true);
  assert.equal(files.includes('src/cli.js'), true);
  assert.equal(files.includes('examples/pi-settings.json'), true);
  assert.equal(files.some(path => /(?:node_modules|test\/|state\.json|service\.log|\.git\/|package-lock)/.test(path)), false);
  const install = join(f.root, 'install'); mkdirSync(install);
  writeFileSync(join(install, 'package.json'), JSON.stringify({ name: 'synthetic-install-check', private: true, type: 'module' }));
  execFileSync('npm', ['install', '--ignore-scripts', '--no-audit', '--no-fund', join(f.root, result.filename)], { cwd: install, encoding: 'utf8', stdio: 'pipe', timeout: 120000 });
  const installed = join(install, 'node_modules', 'pi-subconscious');
  const manifest = JSON.parse(readFileSync(join(installed, 'package.json'), 'utf8'));
  for (const range of Object.values(manifest.peerDependencies)) assert.equal(range, '*');
  assert.equal(manifest.dependencies, undefined);
  const sdkRoot = join(install, 'node_modules', '@earendil-works', 'pi-coding-agent');
  const cli = join(sdkRoot, 'dist', 'bundle', 'cli.js');
  execFileSync(process.execPath, [cli, 'install', installed], { cwd: f.workspace, env: { ...process.env, PI_CODING_AGENT_DIR: f.agentDir }, encoding: 'utf8', stdio: 'pipe', timeout: 30000 });
  const settings = JSON.parse(readFileSync(join(f.agentDir, 'settings.json'), 'utf8'));
  assert.equal(settings.packages.length, 1);
  const service = await startService(f.config, { schedule: false });
  t.after(() => service.close());
  const check = join(install, 'check.mjs');
  writeFileSync(check, `
    import assert from 'node:assert/strict';
    const {createAgentSession, DefaultResourceLoader, SessionManager} = await import('@earendil-works/pi-coding-agent');
    const loader = new DefaultResourceLoader({cwd:${JSON.stringify(f.workspace)},agentDir:${JSON.stringify(f.agentDir)}});
    await loader.reload();
    assert.equal(loader.getExtensions().errors.length,0,JSON.stringify(loader.getExtensions().errors));
    assert.equal(loader.getExtensions().warnings?.length??0,0,JSON.stringify(loader.getExtensions().warnings));
    const manager = SessionManager.create(${JSON.stringify(f.workspace)},${JSON.stringify(join(f.agentDir, 'sessions', 'artifact'))});
    manager.appendMessage({role:'user',content:[{type:'text',text:'Synthetic installation record.'}],timestamp:Date.now()});
    const {session} = await createAgentSession({cwd:${JSON.stringify(f.workspace)},agentDir:${JSON.stringify(f.agentDir)},resourceLoader:loader,sessionManager:manager});
    await session.bindExtensions({mode:'rpc'});
    assert.ok(session.getAllTools().some(tool=>tool.name==='subconscious_reflect'));
    await session.prompt('/subconscious status');
    assert.ok(manager.getEntries().some(entry=>entry.type==='custom_message'&&entry.customType==='pi-clara-subconscious:inspection'));
    await session.extensionRunner.emit({type:'session_shutdown',reason:'quit'});
    session.dispose();
    console.log('Clean artifact loaded through Pi package discovery.');
  `);
  // The server must remain responsive while the child exercises its extension.
  const { spawn } = await import('node:child_process');
  const child = spawn(process.execPath, [check], { cwd: install, stdio: ['ignore', 'pipe', 'pipe'] });
  let stdout = '', stderr = '';
  child.stdout.on('data', data => { stdout += data; }); child.stderr.on('data', data => { stderr += data; });
  const code = await new Promise(resolve => child.once('exit', resolve));
  assert.equal(code, 0, stderr);
  assert.match(stdout, /Clean artifact loaded/);
});
