import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { startService } from '../src/service.js';
import { PiProcess } from '../src/rpc.js';
import { fixture } from './helpers.js';

const repository = fileURLToPath(new URL('..', import.meta.url));
test('a clean package uses the installed Pi without installing another runtime', { timeout: 30000 }, async t => {
  const f = fixture(t, { initiallyPaused: true });
  const packed = JSON.parse(execFileSync('npm', ['pack', '--json', '--pack-destination', f.root], { cwd: repository, encoding: 'utf8' }));
  const result = Array.isArray(packed) ? packed[0] : Object.values(packed)[0];
  assert.equal(result.files.some(file => /(?:node_modules|test\/|state\.json|service\.log|\.git\/|package-lock)/.test(file.path)), false);
  const install = join(f.root, 'install'); mkdirSync(install);
  writeFileSync(join(install, 'package.json'), JSON.stringify({ name: 'synthetic-install-check', private: true, type: 'module' }));
  execFileSync('npm', ['install', '--omit=dev', '--legacy-peer-deps', '--ignore-scripts', '--no-audit', '--no-fund', join(f.root, result.filename)], { cwd: install, encoding: 'utf8', stdio: 'pipe', timeout: 15000 });
  const installed = join(install, 'node_modules/pi-subconscious');
  assert.equal(existsSync(join(install, 'node_modules/@earendil-works/pi-coding-agent')), false);
  const settings = JSON.parse(readFileSync(join(f.agentDir, 'settings.json'), 'utf8')); settings.packages = [installed];
  writeFileSync(join(f.agentDir, 'settings.json'), JSON.stringify(settings));
  const service = await startService(f.config, { schedule: false }); t.after(() => service.close());
  const peer = new PiProcess({ cwd: f.workspace, args: ['--no-session', '--offline', '--approve'], env: { ...process.env, PI_CODING_AGENT_DIR: f.agentDir } });
  t.after(() => peer.close());
  await peer.request('get_state');
  assert.ok((await peer.request('get_commands')).commands.some(command => command.name === 'subconscious'));
  await peer.request('prompt', { message: '/subconscious status' });
  const history = await peer.request('get_entries');
  assert.ok(history.entries.some(entry => entry.type === 'custom_message' && entry.customType === 'pi-subconscious:inspection'));
});
